# A tuple is (row, frame). A third value means "rotate the scaled frame by
# this angle before placing it on the fighter canvas". The rotation is used
# only for Ken's sheet, which has no dedicated knocked-down frame.
def _refs(row, first, last=None):
    last = first if last is None else last
    return [(row, index) for index in range(first, last + 1)]


